"""Generate per-trial tuner config files from a trial specification.

Reads a ``trial_spec.yml`` (the canonical description of the experiment) and a
``base.yml`` (shared config template), then materialises one ready-to-run
``configs/tuner_{id}.yml`` file for every trial listed in the spec.

The generator automatically injects two keys that tie the generated config
to the experiment's output directory layout:

* ``basic_config.run_id``      → ``tuner_{trial.id}``
* ``output_config.experiment_name`` → ``{spec.experiment_name}``

Both defaults can be overridden by placing the same dot-path keys in the
trial's ``overrides`` dict.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import Any

from autoslo.config.utils import copy_and_apply_overrides
from autoslo.filesystem.yaml_helpers import dump_yaml, load_yaml


def generate(spec_path: Path) -> list[Path]:
    """Generate tuner config files for every trial in *spec_path*.

    Parameters
    ----------
    spec_path :
        Absolute or relative path to the ``trial_spec.yml`` file.

    Returns
    -------
    list[Path]
        Paths to the generated config files, in spec sort order.
    """
    spec_path = spec_path.resolve()
    spec_dir = spec_path.parent
    spec = load_yaml(spec_path)

    experiment_name: str = spec["experiment_name"]

    base_config_path = spec_dir / "configs" / "base.yml"
    if not base_config_path.exists():
        print(
            f"[generate_trials] ERROR: base config not found: {base_config_path}",
            file=sys.stderr,
        )
        sys.exit(1)

    base_cfg = load_yaml(base_config_path)
    # Strip experiment_meta if accidentally present in the base template.
    base_cfg.pop("experiment_meta", None)

    trials = spec.get("trials", [])
    if not trials:
        print(
            "[generate_trials] WARNING: no trials found in spec.",
            file=sys.stderr,
        )

    generated: list[Path] = []

    for trial in trials:
        tid: str = trial["trial_id"]

        # Trial-level overrides (may include any dot-path key).
        overrides: dict[str, Any] = dict(trial.get("overrides") or {})

        # Framework injections — trial overrides take precedence.
        injections: dict[str, Any] = {
            "basic_config.run_id": f"tuner_{tid}",
            "output_config.experiment_name": experiment_name,
        }
        merged: dict[str, Any] = {**injections, **overrides}

        cfg = copy_and_apply_overrides(base_cfg, merged)

        out_path = spec_dir / "configs" / f"tuner_{tid}.yml"

        try:
            spec_display = spec_path.relative_to(Path.cwd())
        except ValueError:
            spec_display = spec_path

        header = (
            f"# AUTO-GENERATED by generate_trials.py — do not edit by hand.\n"
            f"# Source spec : {spec_display}\n"
            f"# Trial       : {tid!r}\n"
        )
        dump_yaml(cfg, out_path, header_string=header)

        print(f"  [generate_trials] wrote {out_path.relative_to(Path.cwd())}")
        generated.append(out_path)

    return generated


def main() -> None:
    parser = argparse.ArgumentParser(
        description=(
            "Generate per-trial tuner configs from a trial_spec.yml "
            "and a base config template."
        )
    )
    parser.add_argument(
        "spec",
        help="Path to the trial_spec.yml file.",
    )
    args = parser.parse_args()

    spec_path = Path(args.spec)
    if not spec_path.exists():
        parser.error(f"Spec file not found: {spec_path}")

    generated = generate(spec_path)
    configs_dir = spec_path.resolve().parent / "configs"
    try:
        configs_display = configs_dir.relative_to(Path.cwd())
    except ValueError:
        configs_display = configs_dir
    print(
        f"\n[generate_trials] Done — {len(generated)} config(s) written to "
        f"{configs_display}/",
    )


if __name__ == "__main__":
    main()
